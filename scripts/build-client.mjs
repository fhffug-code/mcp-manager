// Bundles the browser entry into the plain script DeepSeek Harness expects:
// window.__ModuleLoader__.load({ id, factory(require) { ... return { inject, apply } } })
import { build } from 'esbuild'
import { access, mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const packageName = '@local/dsh-mcp-workbench'
const bundlePath = join(root, 'lib', 'client.bundle.js')
const outputPath = join(root, 'lib', 'client.js')

/** Resolves the `./x.js` specifiers TypeScript requires to their `.ts`/`.tsx` sources. */
const tsFromJs = {
  name: 'ts-from-js',
  setup(builder) {
    builder.onResolve({ filter: /\.js$/ }, async (args) => {
      if (!args.path.startsWith('.')) return undefined
      const target = join(args.resolveDir, args.path)
      for (const candidate of [target.replace(/\.js$/, '.ts'), target.replace(/\.js$/, '.tsx')]) {
        try {
          await access(candidate)
          return { path: candidate }
        } catch {
          // Try the next extension.
        }
      }
      return undefined
    })
  },
}

await mkdir(join(root, 'lib'), { recursive: true })
await build({
  entryPoints: [join(root, 'src', 'client', 'index.tsx')],
  outfile: bundlePath,
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  jsx: 'automatic',
  external: ['react'],
  plugins: [tsFromJs],
  logLevel: 'warning',
})

const body = await readFile(bundlePath, 'utf8')
const wrapped = [
  '// Generated by scripts/build-client.mjs. Do not edit.',
  'window.__ModuleLoader__.load({',
  `  id: '${packageName}',`,
  '  factory(require) {',
  '    const module = { exports: {} };',
  '    const exports = module.exports;',
  body,
  '    return module.exports;',
  '  },',
  '});',
  '',
].join('\n')

await writeFile(outputPath, wrapped, 'utf8')
await rm(bundlePath)
console.log(`built ${outputPath}`)

